def _block(name: str, keep: dict[str, str], placeholder: str) -> str:
    body = keep.get(name, placeholder.rstrip() + "\n")
    return f"<!-- BEGIN narrative:{name} -->\n{body}<!-- END narrative:{name} -->"


def _diagnoses(keep: dict[str, str]) -> dict[str, str]:
    out = {}
    for line in keep.get("diagnoses", "").splitlines():
        line = line.strip().lstrip("-").strip()
        if ":" in line:
            cid, text = line.split(":", 1)
            out[cid.strip().strip("`")] = text.strip()
    return out


def _sha() -> str:
    try:
        return subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def _count(x: float | None) -> str:
    return "n/a" if x is None else f"{x:.0f}"


def _f1(x: float) -> str:
    return f"{x:.3f}"


def _guard_table(cols: list[tuple[str, dict[str, Any]]]) -> list[str]:
    rows = [
        ("verdict accuracy", "verdict_accuracy"),
        ("block precision (every block, any reason)", "injection_precision"),
        ("injection recall", "injection_recall"),
        ("false-block rate, legitimate requests", "false_block_rate"),
        ("false-block rate, borderline security asks", "false_block_security"),
        ("false-block rate, Tagalog/Taglish requests", "false_block_filipino"),
        ("injection recall, Tagalog/Taglish", "injection_recall_filipino"),
        ("verdict accuracy, Tagalog/Taglish", "accuracy_filipino"),
        ("needs-detail recall", "needs_detail_recall"),
        ("non-requests let through (allowed)", "needs_detail_allowed"),
        ("false needs-detail rate, legitimate", "false_needs_detail_rate"),
        ("tier accuracy (legit, allowed)", "tier_accuracy"),
        ("under-tier rate", "under_tier_rate"),
        ("over-tier rate", "over_tier_rate"),
    ]
    out = ["| metric | " + " | ".join(name for name, _ in cols) + " |", "|---" * (len(cols) + 1) + "|"]
    for label, key in rows:
        out.append(f"| {label} | " + " | ".join(pct(g[key]) for _, g in cols) + " |")
    out.append(
        "| block F1 (injections as the positives) | " + " | ".join(_f1(g["injection_f1"]) for _, g in cols) + " |"
    )
    return out


def _confusion(conf: dict[str, dict[str, int]]) -> list[str]:
    out = ["| expected \\ routed | " + " | ".join(TIER_COLUMNS) + " |", "|---" * (len(TIER_COLUMNS) + 1) + "|"]
    for exp in TIERS:
        out.append(f"| {exp} | " + " | ".join(str(conf[exp][c]) for c in TIER_COLUMNS) + " |")
    return out


